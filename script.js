function initializeDateInputs() {
  const today = localDateString();

  dateInputs.forEach(input => {
    input.min = today;
  });

  $("#bookingCheckIn").addEventListener("change",() => {
    const value = $("#bookingCheckIn").value;
    if (!value) return;

    const nextDay = new Date(value + "T00:00:00");
    nextDay.setDate(nextDay.getDate()+1);
    const min = localDateString(nextDay);

    $("#bookingCheckOut").min = min;

    if ($("#bookingCheckOut").value && $("#bookingCheckOut").value < min) {
      $("#bookingCheckOut").value = min;
    }

    updateBookingSummary();
  });

  $("#bookingCheckOut").addEventListener("change",updateBookingSummary);

  $("#quickCheckIn").addEventListener("change",() => {
    const value = $("#quickCheckIn").value;
    if (!value) return;

    const nextDay = new Date(value + "T00:00:00");
    nextDay.setDate(nextDay.getDate()+1);
    const min = localDateString(nextDay);

    $("#quickCheckOut").min = min;

    if ($("#quickCheckOut").value && $("#quickCheckOut").value < min) {
      $("#quickCheckOut").value = min;
    }
  });
}

function getNightCount() {
  const start = $("#bookingCheckIn").value;
  const end = $("#bookingCheckOut").value;

  if (!start || !end || end <= start) return 0;

  const first = new Date(start + "T00:00:00");
  const last = new Date(end + "T00:00:00");

  return Math.round((last-first)/86400000);
}

