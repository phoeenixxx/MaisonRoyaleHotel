function validateDates(checkIn,checkOut) {
  const today = localDateString();

  if (!checkIn || !checkOut || checkOut <= checkIn) {
    showToast(t("invalidDates"));
    return false;
  }

  if (checkIn < today) {
    showToast(t("invalidPast"));
    return false;
  }

  return true;
}

